/** Single source of truth for the Studio welcome wizard.
 * Preview and final save call the same generator; no parallel terrain model. */
import {createGuidedWorld,type WorldStartMode} from './world-start.ts';
import {parseProject} from './schema.ts';
import {roundedRectOutline} from '../geography/archipelago-params.ts';
import type {ProjectDocument} from './types.ts';

export type WelcomeMode = WorldStartMode|'blank';
export type ReliefPreset = 'gentle'|'balanced'|'rugged';
export interface WelcomeConfig {
  mode:WelcomeMode;
  width:number;
  length:number;
  seed:number;
  relief:ReliefPreset;
  volcano:boolean;
  mountain?:{x:number;z:number}|null;
  volcanoAt?:{x:number;z:number}|null;
}
export const DEFAULT_WELCOME_CONFIG:WelcomeConfig={
  mode:'island',width:4000,length:3000,seed:4242,relief:'balanced',volcano:true,
};
const PRESETS:Record<ReliefPreset,{cliffs:number;scale:number}>={
  gentle:{cliffs:.08,scale:.55},
  balanced:{cliffs:.35,scale:1},
  rugged:{cliffs:.7,scale:1.4},
};
const within=(point:{x:number;z:number},c:WelcomeConfig)=>Number.isFinite(point.x)&&Number.isFinite(point.z)&&Math.abs(point.x)<=c.width/2&&Math.abs(point.z)<=c.length/2;

/** Pure relative to inputs except the new project IDs generated by createGuidedWorld.
 * The stored geography is identical to that rendered by the welcome preview. */
export function buildWelcomeProject(config:WelcomeConfig,name='Mon petit monde'):ProjectDocument {
  if(!Object.prototype.hasOwnProperty.call(PRESETS,config.relief))throw Error('Relief non reconnu');
  if(config.mountain&&!within(config.mountain,config))throw Error('Montagne hors des limites du monde');
  if(config.volcanoAt&&!within(config.volcanoAt,config))throw Error('Volcan hors des limites du monde');
  const p=createGuidedWorld({
    name,mode:config.mode==='blank'?'calm':config.mode,
    width:config.width,length:config.length,seed:config.seed,
    cliffs:config.mode==='blank'?0:PRESETS[config.relief].cliffs,
    volcano:config.mode!=='blank'&&config.volcano,
  });
  const terrain=p.world.terrain;
  if(!terrain||terrain.kind!=='archipelago')throw Error('Terrain initial incompatible');
  const arch=terrain.archipelago;
  if(config.mode==='blank'){
    // A truly simple, editable coastal plane (no placed items or relief features).
    // Coastline stays just inside the world bounds so editing remains possible.
    const hx=config.width*.46,hz=config.length*.46;
    arch.landmasses=[{
      id:'welcome-plain',name:'Terrain simple',
      outline:roundedRectOutline(hx,hz,Math.min(hx,hz)*.2),
      coastNoiseM:0,coastWavelengthM:500,
      beachWidthM:10,shoreHeightM:1,lowlandHeightM:2,hillHeightM:0,cliffs:0,
    }];
    arch.features=[];
    return parseProject(p);
  }
  const scale=PRESETS[config.relief].scale;
  for(const land of arch.landmasses)land.hillHeightM=Math.min(300,land.hillHeightM*scale);
  for(const f of arch.features) {
    if(f.kind==='mountain'||f.kind==='hill')f.heightM=Math.min(1200,f.heightM*scale);
    else if(f.kind==='ridge')f.heightM=Math.min(800,f.heightM*scale);
  }
  const volcanoes=arch.features.filter(f=>f.kind==='volcano');
  if(config.volcano&&!volcanoes.length){
    const radius=Math.max(20,Math.min(config.width,config.length)*.22);
    arch.features.push({id:'welcome-volcano',kind:'volcano',x:0,z:0,radiusM:radius,
      heightM:Math.min(1000,radius*.42),craterRadiusM:radius*.12,craterDepthM:Math.min(120,radius*.05)});
  }
  if(config.volcano&&config.volcanoAt){
    for(const f of arch.features)if(f.kind==='volcano'){f.x=config.volcanoAt.x;f.z=config.volcanoAt.z;break;}
  }
  if(config.mountain){
    arch.features.push({id:'welcome-mountain',kind:'mountain',x:config.mountain.x,z:config.mountain.z,
      radiusM:Math.max(10,Math.min(config.width,config.length)*.18),
      heightM:Math.min(1200,Math.min(config.width,config.length)*.095*scale),roughness:.55});
  }
  return parseProject(p);
}
