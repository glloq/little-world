import { chromium } from 'playwright';
import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { readProjectArchive } from '../src/studio-core/archive.ts';
import { waitForBrowserCondition } from './poll-browser.mjs';
const base = process.env.WORLD_URL ?? 'http://127.0.0.1:5173/little-world/', out = '/tmp/little-world-organic-settlements';
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath: existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : undefined, args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
let checks = 0;
const check = (ok, label) => { assert.ok(ok, label); checks++; console.log('OK', label); };
try {
    const page = await browser.newPage({ viewport: { width: 1540, height: 1080 } }), errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto(base + 'studio/');
    await page.evaluate(async () => { const { flatSettlementProject } = await import('/little-world/tools/settlement-fixture.mjs'), { ProjectStore } = await import('/little-world/src/studio-core/project-store.ts'); await new ProjectStore().create(flatSettlementProject()); });
    await page.reload();
    await page.getByRole('button', { name: 'Reprendre un projet', exact: true }).click();
    await page.getByRole('button', { name: 'Continuer', exact: true }).first().click();
    await page.locator('.viewport canvas').waitFor();
    await page.getByRole('button', { name: 'Villages & villes', exact: true }).click();
    check(await page.getByLabel('Organisation', { exact: true }).inputValue() === 'organic', 'Les nouvelles implantations proposent une organisation organique par défaut');
    await page.getByLabel('Type d’implantation', { exact: true }).selectOption('village');
    await page.getByLabel('Organisation', { exact: true }).selectOption('clusters');
    await page.getByLabel('Point d’intérêt central', { exact: true }).selectOption('market');
    await page.getByRole('button', { name: '3. Personnalisation', exact: true }).click();
    await page.getByLabel('Taille', { exact: true }).selectOption('60');
    await page.getByRole('button', { name: 'Prévisualiser l’implantation', exact: true }).click();
    await page.getByRole('button', { name: 'Créer dans le monde', exact: true }).waitFor();
    check(await page.getByRole('button', { name: 'Créer dans le monde', exact: true }).isEnabled(), 'Les groupes courbes et les équipements possèdent des accès validés');
    const canvas = page.getByLabel('Plan des villages et villes', { exact: true }), handles = async () => JSON.parse(await canvas.getAttribute('data-handles')), hash = () => canvas.getAttribute('data-plan-hash');
    const screen = async (q) => { await canvas.scrollIntoViewIfNeeded(); const box = await canvas.boundingBox(), v = JSON.parse(await canvas.getAttribute('data-view')); return { x: box.x + (q.x - v.minX) / (v.maxX - v.minX) * box.width, y: box.y + (q.z - v.minZ) / (v.maxZ - v.minZ) * box.height }; };
    const drag = async (kind, index, dx, dz) => { const h = (await handles()).find(h => h.kind === kind && (index === undefined || h.index === index)), from = await screen(h), to = await screen({ x: h.x + dx, z: h.z + dz }), before = await hash(); await page.mouse.move(from.x, from.y); await page.mouse.down(); await page.mouse.move(to.x, to.y, { steps: 8 }); await page.mouse.up(); await page.waitForFunction(before => { const c = document.querySelector('canvas[aria-label="Plan des villages et villes"]'); return c?.dataset.planHash && c.dataset.planHash !== before; }, before); await page.getByRole('button', { name: 'Créer dans le monde', exact: true }).waitFor(); return h; };
    check((await handles()).filter(h => h.kind === 'module').length === 5 && (await handles()).filter(h => h.kind === 'house').length === 60, 'Le brouillon expose cinq poignées de groupes et les poignées des maisons');
    const before = (await handles()).find(h => h.kind === 'house' && h.index === 0);
    await drag('house', 0, -2, 1);
    const after = (await handles()).find(h => h.kind === 'house' && h.index === 0);
    check(Math.abs(after.x - before.x + 2) < .05, 'Une maison se déplace directement dans le plan puis son accès est recalculé');
    const other = (await handles()).find(h => h.kind === 'house' && h.index === 40);
    const group = (await handles()).find(h => h.kind === 'module' && h.index === 1), n = Math.hypot(group.x, group.z);
    await drag('module', 1, group.x / n * 2, group.z / n * 2);
    const same = (await handles()).find(h => h.kind === 'house' && h.index === 40);
    check(Math.hypot(other.x - same.x, other.z - same.z) < .01 && await page.getByRole('button', { name: 'Créer dans le monde', exact: true }).isEnabled(), 'Déplacer un quartier conserve son voisin et des accès valides');
    await page.screenshot({ path: out + '/groups-preview.png', fullPage: true });
    await page.getByRole('button', { name: '2. Emplacement', exact: true }).click();
    await page.getByRole('button', { name: 'Réduire le plan', exact: true }).click();
    await page.getByRole('button', { name: 'Dessiner une zone', exact: true }).click();
    for (const q of [{ x: -185, z: -180 }, { x: 175, z: -175 }, { x: 170, z: 185 }, { x: -180, z: 190 }]) {
        const v = await screen(q);
        await page.mouse.click(v.x, v.y);
    }
    const oldHash = await hash();
    await page.keyboard.press('Enter');
    await page.waitForFunction(before => { const c = document.querySelector('canvas[aria-label="Plan des villages et villes"]'); return c?.dataset.planHash && c.dataset.planHash !== before; }, oldHash);
    check(await page.getByRole('button', { name: 'Créer dans le monde', exact: true }).isEnabled(), 'Une zone dessinée sur le terrain recentre et oriente le plan');
    await page.getByRole('button', { name: 'Agrandir le plan', exact: true }).click();
    await page.screenshot({ path: out + '/bounded-preview.png', fullPage: true });
    await canvas.screenshot({ path: out + '/placement-preview.png' });
    await page.getByRole('button', { name: 'Créer dans le monde', exact: true }).click();
    await page.getByRole('button', { name: 'Sauvegarder', exact: true }).click();
    const saved = () => page.evaluate(async () => { const { ProjectStore } = await import('/little-world/src/studio-core/project-store.ts'), store = new ProjectStore(), summary = (await store.list())[0], v = await store.loadProject(summary.projectId); Object.assign(v.document.chunks, await store.loadChunks(summary.projectId, Object.keys(v.document.chunkIndex), v.revision)); return v.document; });
    let p = await saved(), s = Object.values(p.libraries.settlements)[0];
    check(s.buildings.length === 60 && s.recipe.layout.boundary.length === 4 && s.recipe.layout.adjustments.length === 1 && s.recipe.layout.modules.length === 1, 'La source native conserve les groupes, la zone et la retouche individuelle');
    check(Object.values(p.libraries.paths).filter(p => p.id.includes('-street-')).every(p => p.points.length > 6), 'Les rues enregistrées sont réellement courbes');
    const roads = JSON.stringify(p.libraries.paths);
    await page.getByRole('button', { name: 'Modifier ' + s.recipe.name, exact: true }).click();
    await page.getByLabel('Style architectural', { exact: true }).selectOption('white');
    await page.getByRole('button', { name: 'Varier les maisons', exact: true }).click();
    await page.getByRole('button', { name: 'Appliquer les changements', exact: true }).click();
    await page.getByRole('button', { name: 'Sauvegarder', exact: true }).click();
    p = await saved();
    check(JSON.stringify(p.libraries.paths) === roads, 'Changer les façades conserve les rues, les groupes et leurs accès');
    const event = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Exporter ZIP', exact: true }).click();
    const download = await event, archive = readProjectArchive(new Uint8Array(await readFile(await download.path())));
    check(archive.libraries.settlements[s.id].recipe.layout.boundary.length === 4, 'Le ZIP reste rééditable avec sa zone et son organisation');
    await page.reload();
    await page.getByRole('button', { name: 'Reprendre un projet', exact: true }).click();
    await page.getByRole('button', { name: 'Continuer', exact: true }).first().click();
    await page.getByRole('heading', { name: 'Villages & villes', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Modifier ' + s.recipe.name, exact: true }).click();
    await page.getByRole('button', { name: '1. Type', exact: true }).click();
    check(await page.getByLabel('Organisation', { exact: true }).inputValue() === 'clusters', 'L’organisation modulaire est restaurée à la réouverture');
    await page.getByLabel('Maison à modifier', { exact: true }).selectOption(s.buildings[0].id);
    const popup = page.context().waitForEvent('page');
    await page.locator('#header-actions').getByRole('button', { name: 'Jouer ici', exact: true }).click();
    const game = await popup;
    game.on('pageerror', e => errors.push(e.message));
    await game.waitForLoadState();
    check(new URL(game.url()).searchParams.has('studioBuild'), 'La nouvelle implantation passe le compilateur et le lecteur de jeu');
    await game.waitForSelector('#start:not([disabled])', { timeout: 60000 });
    await game.locator('#start').click();
    await game.waitForFunction(() => /Ouvrir/.test(document.querySelector('#action')?.textContent ?? ''), {}, { timeout: 30000 });
    check(true, 'Le joueur atteint une porte de maison orientée selon une rue courbe');
    await game.keyboard.press('KeyE');
    await game.screenshot({ path: out + '/playtest.png' });
    await game.close();
    await page.locator('.settlements-view').getByRole('button', { name: 'Voir en 3D', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('.viewport canvas')?.dataset.idle === 'true');
    await page.screenshot({ path: out + '/studio-overview.png', fullPage: true });
    check(errors.length === 0, errors.join('\n') || 'Aucune erreur JavaScript');
    await writeFile(out + '/browser-report.json', JSON.stringify({ checks, errors }, null, 2));
    console.log({ checks, errors });
}
finally {
    await browser.close();
}
